# all the no system were derived from natural no system 

# the natural no system : 1 to +inf
# the below code gives the value of 1 to 10 natural nos
for i in range(1, 10+1,1):
    print(i,end='')

# the whole no : 0 + natural nos is callled as whole no system 
# prints the values from 0 to 9 
for i in range(1, 10+1,1):
    print(i-1,end ='')

# even nos starting from 2 to +inf
for i in range(1, 10+1,1):
    print(i+i,end='')

# odd nos strating from 1 to + inf 
for i in range(1, 10+1,1):
    print(f'{i+(i-1)}',end='')

