# the stack can be implemented using arraylist i.e, list 
# append() : adds element add element on top of the stack 
# pop() : removes the element from top of the stack / last of list 
st = []
st.append("a")
st.append("b")
st.append("c")

print(st)
# the last element is the first to be remooved from the list 
print(st.pop())
print(st.pop())